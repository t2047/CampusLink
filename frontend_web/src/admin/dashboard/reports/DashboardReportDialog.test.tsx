import { act, cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import type { DashboardReportSnapshot } from './dashboardReportTypes'
import { DashboardReportDialog } from './DashboardReportDialog'

const mocks = vi.hoisted(() => ({ loadSnapshot: vi.fn() }))
vi.mock('./dashboardReportData', () => ({ loadDashboardReportSnapshot: mocks.loadSnapshot }))

